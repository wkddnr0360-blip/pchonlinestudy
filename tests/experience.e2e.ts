import { expect, test } from '@playwright/test'

test('chapter study, source, pixel feedback, and offline review', async ({ page, context, isMobile }) => {
  await page.goto('./')
  await expect(page.getByRole('heading', { name: '박철한의 무한회독' })).toBeVisible()
  await page.evaluate(async () => {
    await navigator.serviceWorker.ready
    if (!navigator.serviceWorker.controller) {
      await new Promise<void>((resolve) => navigator.serviceWorker.addEventListener('controllerchange', () => resolve(), { once: true }))
    }
  })
  await page.getByRole('button', { name: '패치노트' }).click()
  await expect(page.getByRole('dialog')).toContainText('Canary 1.1.0')
  await page.getByRole('button', { name: '닫기' }).click()
  await page.getByRole('link', { name: '학습 시작' }).click()
  await page.getByRole('button', { name: /제1장 헌법의 개념과 헌법학/ }).click()
  await page.getByRole('button', { name: '문제 풀기', exact: true }).click()
  await expect(page.getByText('교재 1번')).toBeVisible()
  await expect(page.getByText('22년 경찰승진')).toBeVisible()
  await page.getByRole('button', { name: 'X 틀리다' }).click()
  await expect(page.getByText('오답노트에 담았어요.')).toBeVisible()
  await expect(page.locator('.encourage-motion')).toBeVisible()
  await page.getByRole('button', { name: '다음' }).click()
  await expect(page.getByText('교재 2번')).toBeVisible()
  await context.setOffline(true)
  await page.reload()
  await expect(page.getByText('교재 2번')).toBeVisible()
  await context.setOffline(false)
  const nav = page.getByRole('navigation', { name: isMobile ? '모바일 주 메뉴' : '주 메뉴', exact: true })
  await nav.getByRole('link', { name: '오답노트' }).click()
  await page.getByRole('button', { name: /교재 1번/ }).click()
  await page.getByRole('button', { name: 'O 옳다' }).click()
  await expect(page.getByRole('region', { name: '정답 및 해설' })).toContainText('[○]')
  await page.getByRole('button', { name: '복습 완료 표시' }).click()
  await expect(page.getByText('복습할 문제가 없어요.')).toBeVisible()
})

test('timed mock survives a reload and submits after its deadline', async ({ page }) => {
  await page.clock.install()
  await page.goto('./#/exam')
  await expect(page.getByLabel('제한 시간 (분)')).toHaveValue('20')
  await page.getByLabel('제한 시간 (분)').fill('1')
  await page.getByRole('button', { name: '모의고사 시작' }).click()
  const options = page.getByRole('group', { name: '보기' }).getByRole('button')
  await expect(options).toHaveCount(4)
  await options.first().click()
  await expect(options.first()).toHaveAttribute('aria-pressed', 'true')
  await page.reload()
  await expect(options.first()).toHaveAttribute('aria-pressed', 'true')
  await page.clock.fastForward(61000)
  await expect(page.getByText('모의고사 결과')).toBeVisible()
  await page.getByRole('button', { name: /^1번/ }).click()
  await expect(page.getByText('기출 출처', { exact: true })).toHaveCount(4)
})

test('random chapter draw and file backup round trip', async ({ page }) => {
  await page.goto('./#/stage/3')
  await page.getByRole('button', { name: /제1장 헌법의 개념과 헌법학/ }).click()
  await page.getByRole('button', { name: '랜덤' }).click()
  await page.getByLabel('풀 문제 수').fill('2')
  await page.getByRole('button', { name: '문제 풀기' }).click()
  await expect(page.getByText('1 / 2')).toBeVisible()
  const first = await page.locator('.question-label strong').textContent()
  await page.getByRole('button', { name: 'O 옳다' }).click()
  await expect(page.getByRole('region', { name: '정답 및 해설' })).toBeVisible()
  await page.getByRole('button', { name: '다음' }).click()
  await expect(page.getByText('2 / 2')).toBeVisible()
  await expect(page.locator('.question-label strong')).not.toHaveText(first!)
  await page.getByRole('link', { name: '학습 기록 설정' }).click()
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: '백업 다운로드' }).click()
  const file = await (await download).path()
  await page.getByLabel('백업 파일 열기').setInputFiles(file)
  await page.getByRole('button', { name: '복원하기' }).click()
  await expect(page.getByText('학습 기록을 복원했습니다.')).toBeVisible()
})
